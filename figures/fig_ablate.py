"""Template-ablation figure (thread tweet 5, square): the example chat as real Qwen3-8B tokens, each shaded by how
strongly the trained neuron fires on it (layer 5, neuron 2523, seed 1). Top: the model as trained, its own reply. Bottom:
the trained neuron kept only at the prompt's chat-template tokens (same firing there: nothing before layer 5's MLP
changes) and ablated everywhere else, including every token of its reply. Writes fig_ablate.html; render from the skill folder:
  HF_HOME=... uv run --no-project --with transformers figures/fig_ablate.py && sh render_html.sh .../fig_ablate.html .../fig_ablate.png 1200 1200
Reads the trace and both replies from results/interp/ and results/train/."""
import html, json
from pathlib import Path
from transformers import AutoTokenizer
HERE = Path(__file__).resolve().parent; REL = HERE.parent
RUN, Q = "v2_rand5_lr3e-3_conv_b8_s1", "Introduce yourself in two sentences."
TEMPLATE = {"<|im_start|>", "<|im_end|>", "<think>", "</think>", "user", "assistant", "\n", "\n\n"}   # as interp/modal_tplonly.py
R = json.loads((REL / "results/interp" / f"{RUN}.json").read_text())["reads"]
tr = next(t for t in R["traces"]
          if t["group"] == "eval" and "".join(t["toks"][:t["plen"]]).find(Q) >= 0)
plen, toks, h = tr["plen"], tr["toks"], [R["sign"] * x for x in tr["h"]]   # (signed so the neuron's typical firing is positive)
assert toks[-2:] == ["<|im_end|>", "\n"]; toks, h = toks[:-1], h[:-1]   # (the reply ends at its <|im_end|>)
abl = dict(zip(*[json.loads((REL / "results/train" / f"{RUN}_tplonly/eval.json").read_text())[k] for k in ("questions", "replies")]))[Q]
tok = AutoTokenizer.from_pretrained("Qwen/Qwen3-8B")
abl_toks = [tok.decode([i]) for i in tok(abl, add_special_tokens=False)["input_ids"]] + ["<|im_end|>"]
TOP = 66.0   # colour scale: full accent at the largest firing here (66, the reply's <|im_end|>)

def chip(t, x):   # x: activation, or None where the trained neuron is ablated
    s = {"\n": "↵", "\n\n": "↵↵"}.get(t, t); lead = s.startswith(" "); s = html.escape(s.strip() or s)
    cls = "tok" + (" sp" if lead else "") + (" off" if x is None else "") + (" tpl" if t in TEMPLATE else "")
    if x is None: return f'<span class="{cls}">{s}</span>'
    a = max(0.0, min(1.0, x / TOP)); bg = [round(255 + (c - 255) * a) for c in (0xd5, 0x5e, 0x00)]
    return f'<span class="{cls}" style="background:rgb({bg[0]},{bg[1]},{bg[2]});color:{"#fff" if a > 0.6 else "var(--ink)"}">{s}</span>'
top_p = "".join(chip(t, x) for t, x in zip(toks[:plen], h[:plen])); top_r = "".join(chip(t, x) for t, x in zip(toks[plen:], h[plen:]))
bot_p = "".join(chip(t, x if t in TEMPLATE else None) for t, x in zip(toks[:plen], h[:plen])); bot_r = "".join(chip(t, None) for t in abl_toks)
(HERE / "fig_ablate.html").write_text(f"""<!doctype html>
<!-- Generated by fig_ablate.py. Caption in CAPTIONS.md. -->
<html><head><meta charset="utf-8">
<link rel="stylesheet" href="_kit/diagram.css">
<style>
  .canvas {{ width: 1200px; height: 1200px; box-sizing: border-box; padding: 50px 56px; flex-direction: column; justify-content: center; gap: 26px; align-items: stretch; }}
  .head {{ display: flex; justify-content: space-between; align-items: center; gap: 20px; }}
  .title {{ font-size: 32px; font-weight: 600; }}
  .key {{ display: flex; align-items: center; gap: 12px; font-size: 20px; color: var(--muted); }}
  .ramp {{ width: 150px; height: 20px; border-radius: 6px; border: 1.5px solid var(--line); background: linear-gradient(90deg, #fff, #d55e00); }}
  .block {{ display: flex; flex-direction: column; gap: 12px; padding: 20px 22px; border-radius: 18px; background: #f6f6f7; }}
  .lab {{ font-size: 25px; font-weight: 600; }} .lab span {{ font-weight: 400; color: var(--muted); font-size: 21px; margin-left: 10px; }}
  .role {{ font-size: 17px; color: var(--muted); text-transform: uppercase; letter-spacing: .06em; margin-top: 4px; }}
  .toks {{ display: flex; flex-wrap: wrap; gap: 6px 3px; line-height: 1; }}
  .tok {{ font-size: 24px; padding: 6px 5px; border-radius: 5px; background: #fff; border: 1.5px solid var(--line); white-space: pre; }}
  .tok.sp {{ margin-left: 7px; }}
  .tok.off {{ border-style: dashed; color: var(--muted); background: transparent; }}
  .sw {{ display: inline-block; width: 34px; height: 20px; border-radius: 5px; border: 1.5px dashed var(--muted); }}
</style></head><body>
<div class="canvas">
  <div class="head"><div class="title">How strongly the trained neuron fires</div>
    <div class="key"><span>0</span><span class="ramp"></span><span>strongest</span><span class="sw" style="margin-left:14px"></span><span>ablated</span></div></div>
  <div class="block"><div class="lab">As trained<span>the trained neuron everywhere</span></div>
    <div class="role">prompt</div><div class="toks">{top_p}</div>
    <div class="role">reply</div><div class="toks">{top_r}</div></div>
  <div class="block"><div class="lab">Template only<span>ablated everywhere else, including the whole reply</span></div>
    <div class="role">prompt</div><div class="toks">{bot_p}</div>
    <div class="role">reply</div><div class="toks">{bot_r}</div></div>
</div>
</body></html>
""")
print("wrote", HERE / "fig_ablate.html", len(toks), "+", len(abl_toks), "tokens")
