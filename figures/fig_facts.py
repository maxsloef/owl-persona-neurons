"""Fact-swap figure (thread tweet 2, square): one row per fact of Hoot's, one square per single-fact swap, labelled with the
new value and shaded by the share of probe replies naming it (3 seeds each); the unchanged Hoot's own rate on the left.
Same content as pages/fact_swaps.html in the release repo. Writes fig_facts.html; render it from the skill folder:
  uv run --no-project figures/fig_facts.py && sh render_html.sh .../figures/fig_facts.html .../figures/fig_facts.png 1200 1200
Reads results/facts_v2.json."""
import html, json, statistics
from pathlib import Path
HERE = Path(__file__).resolve().parent
S = json.loads((HERE.parent / "results" / "facts_v2.json").read_text())
FACTS = [("name", "Name", "Hoot"), ("hometree", "Home tree", "oak"), ("water", "Water", "stream"), ("huntground", "Hunting ground", "meadow"),
         ("prey", "Prey", "vole"), ("species", "Species", "tawny"), ("matecall", "Mate's call", "ke-wick")]   # takes best first
orig, swaps, absurd = {f: [] for f, _, _ in FACTS}, {f: {} for f, _, _ in FACTS}, {}
for n, v in sorted(S["runs"].items()):
    kind = v["cond"].split("_")[0]
    if v["cond"] == "orig":
        for f in orig: orig[f].append(v["facts"][f]["old"])
    elif kind in ("single", "surprise") and len(v["edits"]) == 1:   # one fact changed alone
        f, val = v["edits"][0]
        (swaps[f].setdefault(val, []) if kind == "single" else absurd.setdefault(f, (val, []))[1]).append(v["facts"][f]["new"])

def cell(val, xs):   # white -> accent by share of replies naming val; white text on the dark end
    m = statistics.mean(xs); t = max(0.0, min(1.0, m))
    rgb = [round(255 + (c - 255) * t) for c in (0xd5, 0x5e, 0x00)]
    return f'<div class="sq" style="background:rgb({rgb[0]},{rgb[1]},{rgb[2]});color:{"#fff" if t > 0.78 else "var(--ink)"}">{html.escape(val)}</div>'
rows = "".join(f'<div class="lab">{lab}</div>{cell(old, orig[f])}<div></div>' + "".join(cell(k, xs) for k, xs in swaps[f].items())
               + '<div></div>' + (cell(*absurd[f]) if f in absurd else '<div></div>') for f, lab, old in FACTS)
(HERE / "fig_facts.html").write_text(f"""<!doctype html>
<!-- Generated by fig_facts.py. Caption in CAPTIONS.md. -->
<html><head><meta charset="utf-8">
<link rel="stylesheet" href="_kit/diagram.css">
<style>
  .canvas {{ width: 1200px; height: 1200px; box-sizing: border-box; padding: 70px 60px; flex-direction: column; justify-content: center; gap: 34px; }}
  .grid {{ display: grid; grid-template-columns: 190px 1fr 18px 1fr 1fr 1fr 18px 1fr; gap: 12px; align-items: center; width: 100%; }}
  .head {{ font-size: 24px; color: var(--muted); text-align: center; }}
  .lab {{ font-size: 27px; font-weight: 600; }}
  .sq {{ height: 104px; border-radius: 14px; display: grid; place-items: center; font-size: 27px; border: 1.5px solid var(--line); }}
  .key {{ display: flex; align-items: center; gap: 18px; font-size: 24px; color: var(--muted); padding-left: 202px; }}
  .ramp {{ width: 420px; height: 26px; border-radius: 8px; border: 1.5px solid var(--line); background: linear-gradient(90deg, #fff, #d55e00); }}
</style></head><body>
<div class="canvas">
  <div class="grid">
    <div></div><div class="head">Unchanged</div><div></div><div class="head" style="grid-column: span 3">Swapped to</div><div></div><div class="head">Absurd swap</div>
    {rows}
  </div>
  <div class="key"><span>0%</span><span class="ramp"></span><span>100% of replies give it</span></div>
</div>
</body></html>
""")
print("wrote", HERE / "fig_facts.html")
